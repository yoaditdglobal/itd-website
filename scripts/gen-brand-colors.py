#!/usr/bin/env python3
"""Extract each logo's dominant brand colour → src/lib/brand-colors.ts.

Scans every "/logos/..." path referenced anywhere in src/, ignores near-white,
near-black and grey pixels, and takes the most common saturated colour (hue-
binned, weighted by saturation). Logos with no usable colour are omitted so the
page falls back to its category accent. Re-run after adding a logo:
    python3 scripts/gen-brand-colors.py
"""
import colorsys, os, re, subprocess, tempfile
from collections import defaultdict
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = ""
for dp, _, fs in os.walk(os.path.join(ROOT, "src")):
    for f in fs:
        if f.endswith((".ts", ".tsx")) and f != "brand-colors.ts":
            src += open(os.path.join(dp, f)).read()
paths = sorted(set(re.findall(r'"(/logos/[^"]+\.(?:png|webp|jpg|jpeg|svg|avif))"', src)))

def load(path):
    full = os.path.join(ROOT, "public", path.lstrip("/"))
    if not os.path.exists(full):
        return None
    if full.endswith(".svg"):
        out = tempfile.mkdtemp()
        subprocess.run(["qlmanage", "-t", "-s", "256", "-o", out, full], capture_output=True)
        png = os.path.join(out, os.path.basename(full) + ".png")
        if not os.path.exists(png):
            return None
        full = png
    try:
        im = Image.open(full).convert("RGBA")
    except Exception:
        return None
    im.thumbnail((96, 96))
    return im

colors = {}
for p in paths:
    im = load(p)
    if im is None:
        continue
    bins = defaultdict(lambda: [0.0, 0.0, 0.0, 0.0])  # weight, r, g, b sums
    for r, g, b, a in im.getdata():
        if a < 128:
            continue
        h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
        if s < 0.35 or l < 0.12 or l > 0.9:
            continue  # grey / near-black / near-white
        w = s * (1 - abs(l - 0.5))
        k = int(h * 24)
        bins[k][0] += w; bins[k][1] += r * w; bins[k][2] += g * w; bins[k][3] += b * w
    if not bins:
        continue
    total = sum(v[0] for v in bins.values())
    k, v = max(bins.items(), key=lambda kv: kv[1][0])
    if v[0] / max(total, 1e-9) < 0.25 or v[0] < 8:
        continue
    r, g, b = (int(v[i] / v[0]) for i in (1, 2, 3))
    colors[p] = f"#{r:02x}{g:02x}{b:02x}"

lines = ["// GENERATED by scripts/gen-brand-colors.py — do not edit by hand.",
         "// Dominant brand colour per logo; missing = no usable colour (falls back",
         "// to the page's category accent).",
         "export const BRAND_COLORS: Record<string, string> = {"]
lines += [f'  "{k}": "{v}",' for k, v in colors.items()]
lines += ["};", ""]
open(os.path.join(ROOT, "src/lib/brand-colors.ts"), "w").write("\n".join(lines))
print(f"{len(colors)}/{len(paths)} logos coloured")
